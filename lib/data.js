export function mergeState(saved) {
  const base = structuredClone(seed);
  const users = Array.isArray(saved.users) && saved.users.length ? saved.users : base.users;
  const cars = Array.isArray(saved.cars) && saved.cars.length ? saved.cars : base.cars;
  const views = ["dashboard", "service", "photos", "maintenance", "profile"];
  return {
    sessionUserId: users.some((user) => user.id === saved.sessionUserId) ? saved.sessionUserId : null,
    view: views.includes(saved.view) ? saved.view : "dashboard",
    activeCarId: cars.some((car) => car.id === saved.activeCarId) ? saved.activeCarId : cars[0].id,
    users,
    cars,
    repairs: Array.isArray(saved.repairs) ? saved.repairs : base.repairs,
    plans: Array.isArray(saved.plans) ? saved.plans : base.plans,
    photos: Array.isArray(saved.photos) ? saved.photos : base.photos,
    logs: Array.isArray(saved.logs) ? saved.logs : base.logs,
  };
}
